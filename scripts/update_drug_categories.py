def classify_chemical(name):
    for keywords, cat in CHEMICAL_CLASSIFICATION:
        for kw in keywords:
            if kw in name:
                return cat
    return "M01 其他西药"


def classify_tcm(name, indication):
    if name in TCM_NAME_SPECIAL:
        return TCM_NAME_SPECIAL[name]
    if indication:
        for keywords, cat in TCM_INDICATION_MAP:
            for kw in keywords:
                if kw in indication:
                    return cat
    return "L14 中成药-其他"


def determine_new_category(drug_name, old_category, indication):
    if old_category and "中成药" in old_category:
        return classify_tcm(drug_name, indication)
    # 名称里带“颗粒/丸/胶囊/口服液”且没有明显西药关键词的，按中成药处理
    if any(k in drug_name for k in ["颗粒", "丸", "口服液", "糖浆", "膏方", "散", "滴丸"]):
        return classify_tcm(drug_name, indication)
    return classify_chemical(drug_name)


def main():
    print("=" * 60)
    print("  药品分类体系升级工具")
    print("=" * 60)

    conn = pymysql.connect(**MYSQL_CONFIG)
    cursor = conn.cursor()
    cursor.execute("SELECT id, drug_name, drug_category, indication FROM drugs")
    rows = cursor.fetchall()

    updates = []
    stats = {}
    unchanged = 0

    for drug_id, drug_name, old_category, indication in rows:
        new_cat = determine_new_category(drug_name, old_category, indication)
        if new_cat != old_category:
            updates.append((new_cat, drug_id, drug_name, old_category, new_cat))
            stats[new_cat] = stats.get(new_cat, 0) + 1
        else:
            unchanged += 1

    print(f"\n总数: {len(rows)}  需要更新: {len(updates)}  无需更改: {unchanged}")

    if not updates:
        print("没有需要更新的记录，退出。")
        cursor.close()
        conn.close()
        return

    # 生成回滚 SQL
    output_path = "update_drug_categories.sql"
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("-- ============================================================\n")
        f.write("--  药品分类体系升级 SQL - 旧分类→新13类标准体系\n")
        f.write(f"--  共 {len(updates)} 条 UPDATE 语句\n")
        f.write("-- ============================================================\n\n")
        f.write("USE `medical_data`;\n\n")
        for new_cat, drug_id, name, old_cat, _ in updates:
            safe_cat = new_cat.replace("'", "''")
            f.write(f"UPDATE `drugs` SET `drug_category` = '{safe_cat}' WHERE `id` = {drug_id};  -- {name}: {old_cat} → {new_cat}\n")

    print(f"\nSQL 文件已生成: {os.path.abspath(output_path)}")

    # 直接执行更新
    print("\n开始更新数据库...")
    try:
        for new_cat, drug_id, name, old_cat, _ in updates:
            cursor.execute("UPDATE drugs SET drug_category = %s WHERE id = %s", (new_cat, drug_id))
        conn.commit()
        print(f"✓ 成功更新 {len(updates)} 条记录")
    except Exception as e:
        conn.rollback()
        print(f"✗ 更新失败，已回滚: {e}")
        raise
    finally:
        cursor.close()
        conn.close()

    print("\n新分类分布:")
    for cat, count in sorted(stats.items(), key=lambda x: -x[1]):
        print(f"  {cat}: {count} 种")


if __name__ == "__main__":
    main()
