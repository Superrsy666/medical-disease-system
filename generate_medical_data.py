def generate_approval_number(index, category):
    prefix_map = {"化学药品": "H", "中成药": "Z", "生物制品": "S", "抗生素": "H"}
    prefix = prefix_map.get(category, "H")
    year = 2020 - (index % 25)
    num = str(100000 + (index * 7) % 899999)
    return f"国药准字{prefix}{year}{num}"


