def generate_chemical_drugs():
    drugs = []
    for prefix in CHEMICAL_PREFIXES:
        # 每个前缀生成3-5种剂型
        suffixes = random.sample(CHEMICAL_SUFFIXES, random.randint(3, 5))
        for suffix in suffixes:
            drug_name = prefix + suffix
            if len(drug_name) < 3 or len(drug_name) > 30:
                continue
            drugs.append(drug_name)
    return list(set(drugs))

