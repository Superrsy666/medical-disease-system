# ============================================================

def generate_all_data():
    output_path = os.path.join(OUTPUT_DIR, "medical_data_full.sql")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("-- ============================================================\n")
        f.write("--  医疗疾病系统 - 大规模数据生成脚本\n")
        f.write(f"--  生成时间: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write("--  包含: 130+ 疾病、1100+ 药品、疾病-药品关联\n")
        f.write("-- ============================================================\n\n")

        f.write("USE `medical_data`;\n\n")

        # ---- 清空旧数据 ----
        f.write("-- 清空旧数据（按依赖顺序）\n")
        f.write("SET FOREIGN_KEY_CHECKS = 0;\n")
        f.write("TRUNCATE TABLE `disease_drug_relation`;\n")
        f.write("TRUNCATE TABLE `drugs`;\n")
        f.write("TRUNCATE TABLE `diseases`;\n")
        f.write("SET FOREIGN_KEY_CHECKS = 1;\n\n")

        # ---- 疾病数据 ----
        f.write("-- ============================================================\n")
        f.write("--  1. 疾病数据\n")
        f.write("-- ============================================================\n\n")

        f.write("INSERT INTO `diseases` (`disease_name`, `icd_code`, `category_path`, `description`, `symptoms`) VALUES\n")
        values = []
        for d in DISEASES:
            name, icd, cat, desc, symptoms = d
            values.append(f"({escape_sql(name)}, {escape_sql(icd)}, {escape_sql(cat)}, {escape_sql(desc)}, {escape_sql(symptoms)})")
        f.write(",\n".join(values) + ";\n\n")

        print(f"疾病数据: {len(DISEASES)} 条")

        # ---- 药品数据 ----
        f.write("-- ============================================================\n")
        f.write("--  2. 药品数据\n")
        f.write("-- ============================================================\n\n")

        all_drugs = []
        drug_index = 0

        # 中成药（使用新分类体系）
        for item in CHINESE_PATENT_MEDICINES:
            name, old_category, indication, _ = item
            category = classify_tcm(name, indication)
            prefix = generate_approval_number_new(category)
            approval = generate_approval_number(drug_index, prefix)
            manufacturer = pick_manufacturer(drug_index)
            spec = pick_specification(drug_index)
            dosage = pick_dosage_form(name)
            date = generate_approval_date(drug_index)
            all_drugs.append((name, generate_english_name(name), approval, manufacturer, dosage, spec, indication, category, date, "36个月"))
            drug_index += 1

        # 化学药品（使用新分类体系）
        for name in CHEMICAL_DRUG_NAMES:
            eng = generate_english_name(name)
            category = classify_chemical_drug(name)
            prefix = generate_approval_number_new(category)
            approval = generate_approval_number(drug_index, prefix)
            manufacturer = pick_manufacturer(drug_index)
            spec = pick_specification(drug_index)
            dosage = pick_dosage_form(name)
            date = generate_approval_date(drug_index)
            indication = f"用于治疗{name}相关疾病。"
            all_drugs.append((name, eng, approval, manufacturer, dosage, spec, indication, category, date, "24个月"))
            drug_index += 1

        # 去重（按药品名称）
        seen_names = set()
        unique_drugs = []
        for d in all_drugs:
            if d[0] not in seen_names:
                seen_names.add(d[0])
                unique_drugs.append(d)

        f.write("INSERT INTO `drugs` (`drug_name`, `english_name`, `approval_number`, `manufacturer`, `dosage_form`, `specification`, `indication`, `drug_category`, `approval_date`, `validity_period`) VALUES\n")
        values = []
        for d in unique_drugs:
            values.append(f"({escape_sql(d[0])}, {escape_sql(d[1])}, {escape_sql(d[2])}, {escape_sql(d[3])}, {escape_sql(d[4])}, {escape_sql(d[5])}, {escape_sql(d[6])}, {escape_sql(d[7])}, {escape_sql(d[8])}, {escape_sql(d[9])})")
        f.write(",\n".join(values) + ";\n\n")

        print(f"药品数据: {len(unique_drugs)} 条")

        # ---- 疾病-药品关联 ----
        f.write("-- ============================================================\n")
        f.write("--  3. 疾病-药品关联数据\n")
        f.write("-- ============================================================\n\n")

        # 构建疾病名称 -> ID 映射
        disease_name_to_id = {}
        for i, d in enumerate(DISEASES):
            disease_name_to_id[d[0]] = i + 1

        # 构建药品名称 -> ID 映射
        drug_name_to_id = {}
        for i, d in enumerate(unique_drugs):
            drug_name_to_id[d[0]] = i + 1

        # 生成关联
        relations = []
        for disease_name, drug_keywords in DISEASE_DRUG_RULES.items():
            disease_id = disease_name_to_id.get(disease_name)
            if disease_id is None:
                continue
            for keyword in drug_keywords:
                # 查找匹配的药品
                matched_drug_ids = []
                for drug_name, drug_id in drug_name_to_id.items():
                    if keyword in drug_name:
                        matched_drug_ids.append(drug_id)
                # 最多取 5 个匹配
                for drug_id in matched_drug_ids[:5]:
                    relations.append((disease_id, drug_id, "indication"))

        # 去重
        unique_relations = list(set(relations))

        f.write("INSERT INTO `disease_drug_relation` (`disease_id`, `drug_id`, `match_source`) VALUES\n")
        values = []
        for r in unique_relations:
            values.append(f"({r[0]}, {r[1]}, {escape_sql(r[2])})")
        f.write(",\n".join(values) + ";\n\n")

        print(f"疾病-药品关联: {len(unique_relations)} 条")

        f.write("-- ============================================================\n")
        f.write("--  数据生成完成\n")
        f.write("-- ============================================================\n")

    print(f"\nSQL 文件已生成: {output_path}")
    return output_path


